"""Durable room/chat backend. Credentials come only from the server environment.

A deployment claims the writer lease while restoring rooms. A replaced process
can finish reads, but cannot overwrite the new process's confirmed snapshots.
There is deliberately no temporary-disk fallback on a PostgreSQL failure.
"""
import hashlib
import json
import os
import threading
import time
import uuid
from contextlib import contextmanager

from network_storage import StorageError, expiry, snapshot

_OWNER = str(uuid.uuid4())
_SCHEMA_LOCK = threading.Lock()
_schema_ready = False
_claimed = False


def rollback(db):
    if db is not None:
        try:
            db.rollback()
        except Exception:
            pass


@contextmanager
def transaction():
    global _schema_ready
    db = None
    try:
        import psycopg
        dsn = os.environ.get('RPG_DATABASE_URL') or os.environ['DATABASE_URL']
        sslmode = psycopg.conninfo.conninfo_to_dict(dsn).get('sslmode', 'require')
        if sslmode not in ('require', 'verify-ca', 'verify-full'):
            sslmode = 'require'
        db = psycopg.connect(dsn, connect_timeout=15, sslmode=sslmode,
                             application_name='heart-of-darkness')
        namespace = os.environ.get('RPG_DATABASE_SCHEMA', 'public')
        search_path = psycopg.sql.SQL('SET LOCAL search_path TO {}').format(psycopg.sql.Identifier(namespace))
        db.execute(search_path)
        with _SCHEMA_LOCK:
            if not _schema_ready:
                db.execute('SELECT pg_advisory_xact_lock(719062508)')
                db.execute('CREATE TABLE IF NOT EXISTS room_saves (code TEXT PRIMARY KEY, updated_at BIGINT NOT NULL, expires_at BIGINT NOT NULL, state TEXT NOT NULL)')
                db.execute('CREATE TABLE IF NOT EXISTS rpg_writer (id INTEGER PRIMARY KEY CHECK(id=1), owner TEXT NOT NULL)')
                db.execute('CREATE TABLE IF NOT EXISTS party_chat (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, room TEXT NOT NULL, player TEXT NOT NULL, name TEXT NOT NULL, hero TEXT, text TEXT NOT NULL, ts DOUBLE PRECISION NOT NULL, nonce TEXT NOT NULL, UNIQUE(room,player,nonce))')
                db.execute('CREATE INDEX IF NOT EXISTS chat_room_id ON party_chat(room,id)')
                db.commit()
                _schema_ready = True
                db.execute(search_path)
        yield db
        db.commit()
    except (StorageError, OverflowError):
        rollback(db)
        raise
    except Exception:
        rollback(db)
        # Do not expose connection strings/passwords in logs or HTTP responses.
        raise StorageError('Persistent database unavailable; no temporary save was used.') from None
    finally:
        if db is not None:
            db.close()


def guard_writer(db):
    row = db.execute('SELECT owner FROM rpg_writer WHERE id=1 FOR SHARE').fetchone()
    if not _claimed or not row or row[0] != _OWNER:
        raise StorageError('This server was replaced. Retry on the new deployment.')


def save(room):
    record = snapshot(room)
    updated = int(record.get('gameUpdatedAt') or record.get('lastActiveAt') or record.get('createdAt') or time.time())
    with transaction() as db:
        guard_writer(db)
        db.execute('INSERT INTO room_saves(code,updated_at,expires_at,state) VALUES(%s,%s,%s,%s) ON CONFLICT(code) DO UPDATE SET updated_at=EXCLUDED.updated_at,expires_at=EXCLUDED.expires_at,state=EXCLUDED.state',
                   (record['code'], updated, expiry(record), json.dumps(record, ensure_ascii=False, separators=(',', ':'))))


def remove(codes):
    if not codes:
        return
    with transaction() as db:
        guard_writer(db)
        for code in codes:
            db.execute('DELETE FROM party_chat WHERE room=%s', (code,))
            db.execute('DELETE FROM room_saves WHERE code=%s', (code,))


def restore(now=None):
    global _claimed
    now = int(time.time() if now is None else now)
    output = {}
    with transaction() as db:
        if not _claimed:
            db.execute('INSERT INTO rpg_writer(id,owner) VALUES(1,%s) ON CONFLICT(id) DO UPDATE SET owner=EXCLUDED.owner', (_OWNER,))
        else:
            guard_writer(db)
        rows = db.execute('SELECT code,state FROM room_saves').fetchall()
        for code, text in rows:
            record = json.loads(text)
            if not isinstance(record, dict) or record.get('code') != code or not isinstance(record.get('players'), dict):
                raise StorageError('A stored room is invalid; startup was stopped without deleting it.')
            if record.get('started') and not record.get('lastPlayerSeenAt'):
                record['lastPlayerSeenAt'] = int(record.get('gameUpdatedAt') or record.get('lastActiveAt') or record.get('createdAt') or 0)
            if expiry(record) <= now:
                db.execute('DELETE FROM party_chat WHERE room=%s', (code,))
                db.execute('DELETE FROM room_saves WHERE code=%s', (code,))
            else:
                output[code] = record
    _claimed = True
    return output


def chat_history(code, after=0):
    with transaction() as db:
        rows = db.execute('SELECT id,player,name,hero,text,ts FROM (SELECT * FROM party_chat WHERE room=%s ORDER BY id DESC LIMIT 300) AS recent WHERE id>%s ORDER BY id', (code, after)).fetchall()
    return [dict(zip(('id', 'playerId', 'name', 'heroId', 'text', 'time'), row)) for row in rows]


def chat_send(code, player, text, nonce):
    if not isinstance(text, str) or not text.strip() or len(text) > 500:
        raise ValueError('Сообщение: от 1 до 500 символов')
    if not isinstance(nonce, str) or not 8 <= len(nonce) <= 80:
        raise ValueError('Некорректный идентификатор сообщения')
    with transaction() as db:
        guard_writer(db)
        # Serialize deduplication and rate checking for this room/player only.
        lock = int.from_bytes(hashlib.sha256((code + ':' + player['id']).encode()).digest()[:8], 'big', signed=True)
        db.execute('SELECT pg_advisory_xact_lock(%s)', (lock,))
        old = db.execute('SELECT id FROM party_chat WHERE room=%s AND player=%s AND nonce=%s', (code, player['id'], nonce)).fetchone()
        if old:
            return old[0]
        now = time.time()
        last = db.execute('SELECT MAX(ts) FROM party_chat WHERE room=%s AND player=%s', (code, player['id'])).fetchone()[0]
        if last and now - last < 1:
            raise OverflowError('Подожди секунду перед следующим сообщением')
        row = db.execute('INSERT INTO party_chat(room,player,name,hero,text,ts,nonce) VALUES(%s,%s,%s,%s,%s,%s,%s) RETURNING id',
                         (code, player['id'], player['name'], player.get('heroId'), text.strip(), now, nonce)).fetchone()
        db.execute('DELETE FROM party_chat WHERE room=%s AND id NOT IN (SELECT id FROM party_chat WHERE room=%s ORDER BY id DESC LIMIT 300)', (code, code))
        return row[0]
